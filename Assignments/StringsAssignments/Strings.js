
let str = 'Selenium';

// Print using escape character
console.log("Hi I'm learning \"Selenium\" ");

//toUpperCase() and toLowerCase()
console.log(str.toUpperCase());
console.log(str.toLowerCase());

// length
console.log(str.length);

// charAt()
console.log(str.charAt(5));

// indexOf()
console.log(str.indexOf('i'));

// includes
console.log(str.includes('niu'));
console.log(str.includes('niu', 2));

// startsWith()
console.log(str.startsWith('Sel'));

// endsWith()
console.log(str.endsWith('um'));

// subString()
console.log(str.substring(2, 6));

// replace
console.log(str.replace('e', 'o'));

// replaceAll
console.log(str.replaceAll('e', 'p'));

